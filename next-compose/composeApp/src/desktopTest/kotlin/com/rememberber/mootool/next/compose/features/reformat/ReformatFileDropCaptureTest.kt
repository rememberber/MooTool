/** F03 文件 Tab `.file-drop-row` Compose Tab 焦点帧（非产品主窗）。 */
class ReformatFileDropCaptureTest {
    @OptIn(ExperimentalTestApi::class)
    @Test
    fun captureReformatFileDropTabFocus() = runDesktopComposeUiTest(width = 420, height = 120) {
        val zh = Translator(AppLanguage.ZhCN)
        val focus = FocusRequester()
        setContent {
            MooTheme(preference = ThemePreference.Light, systemDark = false, interfaceStyle = "modern") {
                val colors = MooTheme.colors
                Row(
                    Modifier
                        .background(colors.workspace)
                        .padding(12.dp)
                        .mooFileDropRow(),
                    horizontalArrangement = Arrangement.spacedBy(10.dp),
                ) {
                    MooButton(
                        zh.t("reformat.chooseFile"),
                        p5Toolbar = true,
                        onClick = {},
                        modifier = Modifier.focusRequester(focus),
                    )
                    Text(zh.t("reformat.noFile"), color = colors.textMuted, fontSize = 11.sp)
                }
            }
        }
        val cwd = File(".").canonicalFile
        val root = if (cwd.name == "composeApp") cwd.parentFile else cwd
        val dir = File(root, "docs/evidence/2026-09-15-inspector-screencapture/windows")
        dir.mkdirs()
        val expected = 0x316DC0
        runOnIdle { focus.requestFocus() }
        waitForIdle()
        val file = File(dir, "167-compose-reformat-file-drop-tab-focus.png")
        val image = onRoot().captureToImage().toAwtImage()
        assertTrue(ImageIO.write(image, "png", file))
        assertTrue(countRingPixels(image, expected) >= 8, "reformat file drop focus ring")
    }

    private fun countRingPixels(image: java.awt.image.BufferedImage, rgb: Int): Int {
        var hits = 0
        for (y in 0 until image.height) {
            for (x in 0 until image.width) {
                if (image.getRGB(x, y) and 0x00FFFFFF == rgb) hits++
            }
        }
        return hits
    }
}
