/// Navigation and workbench strings aligned with Electron `messages.ts` (`app.nav.*`, `app.group.*`).
public enum AppLocalization {
    public static func toolTitle(_ toolID: String, language: AppLanguage) -> String {
        table[language]?[toolID] ?? table[.zhCN]?[toolID] ?? toolID
    }

    public static func toolSubtitle(_ toolID: String, language: AppLanguage, fallback: String) -> String {
        subtitleTable[language]?[toolID] ?? subtitleTable[.zhCN]?[toolID] ?? fallback
    }

    public static func groupTitle(_ group: String, language: AppLanguage) -> String {
        if let key = groupKeys[group], let value = groupTable[language]?[key] { return value }
        return group
    }

    public static func string(_ key: String, language: AppLanguage) -> String {
        ui[language]?[key] ?? ui[.zhCN]?[key] ?? key
    }

    public static func preferredLanguage() -> AppLanguage {
        let suffix = ProcessInfo.processInfo.environment["MOOTOOL_NATIVE_TEST_DATA"] == nil ? "" : ".acceptance"
        if let code = UserDefaults(suiteName: Product.bundleID + suffix)?.string(forKey: "general.language"), !code.isEmpty {
            return AppLanguage.normalized(code)
        }
        return .zhCN
    }

    public static func format(_ key: String, language: AppLanguage, replacements: [String: String] = [:]) -> String {
        var text = string(key, language: language)
        for (placeholder, value) in replacements {
            text = text.replacingOccurrences(of: "{\(placeholder)}", with: value)
        }
        return text
    }

