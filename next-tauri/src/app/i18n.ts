export interface Translator {
  locale: AppLanguage
  t(key: MessageKey, values?: Record<string, string | number>): string
  toolTitle(tool: ToolDefinition): string
  groupTitle(group: ToolDefinition['group']): string
}

export function useI18n(): Translator {
  const { settings } = useSettings()
  return useMemo(() => createTranslator(settings.general.language), [settings.general.language])
}

export function createTranslator(locale: AppLanguage): Translator {
  return {
    locale,
    t: (key, values) => format(messages[locale][key], values),
    toolTitle: (tool) => toolTitles[tool.id]?.[locale] ?? tool.title,
    groupTitle: (group) => groupTitles[group][locale]
  }
}

function format(template: string, values?: Record<string, string | number>): string {
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(values[key] ?? `{${key}}`))
}

